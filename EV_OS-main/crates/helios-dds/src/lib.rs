//! Safe HELIOS wrapper over Cyclone DDS.
//!
//! All `unsafe` in the HELIOS software stack outside the bare-metal BSP lives in
//! this file and `helios-dds-sys`. Invariants upheld here:
//! * every entity handle is created and deleted exactly once (RAII, `Drop`);
//! * topic types are `#[repr(C)]` fixed-size PODs generated from the IDL by
//!   bindgen, so writing from `&T` and taking into `&mut T` is sound;
//! * descriptors are the `idlc`-generated statics for exactly those types.

use core::ffi::c_void;
use core::marker::PhantomData;
use helios_dds_sys as sys;
use std::ffi::CString;
use std::time::{Duration, Instant};

pub use sys::helios_DriveModeRequest as DriveModeRequest;
pub use sys::helios_VehicleTelemetry as VehicleTelemetry;

/// HELIOS vehicle domain.
pub const HELIOS_DOMAIN: u32 = 42;
pub const TOPIC_TELEMETRY: &str = "helios/vehicle/telemetry";
pub const TOPIC_DRIVE_MODE: &str = "helios/cockpit/drive_mode_request";

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("Cyclone DDS call `{call}` failed with {code}")]
    Dds { call: &'static str, code: i32 },
    #[error("timed out waiting for {0}")]
    Timeout(&'static str),
    #[error("invalid string argument")]
    Nul(#[from] std::ffi::NulError),
}

pub type Result<T> = std::result::Result<T, Error>;

fn check(call: &'static str, rc: i32) -> Result<i32> {
    if rc < 0 { Err(Error::Dds { call, code: rc }) } else { Ok(rc) }
}

/// Marker for IDL types with an `idlc` topic descriptor.
///
/// # Safety
/// `descriptor()` must return the descriptor generated for exactly `Self`, and
/// `Self` must be a fixed-size `#[repr(C)]` type with no pointers.
pub unsafe trait Topic: Copy + Default {
    fn descriptor() -> *const sys::dds_topic_descriptor_t;
}

// SAFETY: descriptors generated by idlc for these exact bindgen structs; both are
// fixed-size (arrays only, no strings/sequences), checked by bindgen layout tests.
unsafe impl Topic for VehicleTelemetry {
    fn descriptor() -> *const sys::dds_topic_descriptor_t {
        &raw const sys::helios_VehicleTelemetry_desc
    }
}
// SAFETY: as above.
unsafe impl Topic for DriveModeRequest {
    fn descriptor() -> *const sys::dds_topic_descriptor_t {
        &raw const sys::helios_DriveModeRequest_desc
    }
}

/// QoS profiles used across HELIOS.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum QosProfile {
    /// Periodic state (telemetry): best-effort, volatile, keep-last 1.
    Telemetry,
    /// Commands / configuration: reliable, transient-local, keep-last 1.
    Command,
    /// Loss-intolerant streams (logging, HIL capture): reliable, volatile, keep-last 64.
    /// Keep-last 1 lets a late `take` see an overwritten sample (observed 1/5000 at 1 kHz).
    Stream,
}

struct Qos(*mut sys::dds_qos_t);

impl Qos {
    fn new(p: QosProfile) -> Self {
        // SAFETY: dds_create_qos returns an owned qos object freed in Drop.
        let q = unsafe { sys::dds_create_qos() };
        // SAFETY: q is a valid qos object.
        unsafe {
            match p {
                QosProfile::Telemetry => {
                    sys::dds_qset_reliability(q, sys::dds_reliability_kind_DDS_RELIABILITY_BEST_EFFORT, 0);
                    sys::dds_qset_durability(q, sys::dds_durability_kind_DDS_DURABILITY_VOLATILE);
                    sys::dds_qset_history(q, sys::dds_history_kind_DDS_HISTORY_KEEP_LAST, 1);
                }
                QosProfile::Stream => {
                    sys::dds_qset_reliability(q, sys::dds_reliability_kind_DDS_RELIABILITY_RELIABLE, 100_000_000);
                    sys::dds_qset_durability(q, sys::dds_durability_kind_DDS_DURABILITY_VOLATILE);
                    sys::dds_qset_history(q, sys::dds_history_kind_DDS_HISTORY_KEEP_LAST, 64);
                }
                QosProfile::Command => {
                    sys::dds_qset_reliability(q, sys::dds_reliability_kind_DDS_RELIABILITY_RELIABLE, 100_000_000);
                    sys::dds_qset_durability(q, sys::dds_durability_kind_DDS_DURABILITY_TRANSIENT_LOCAL);
                    sys::dds_qset_history(q, sys::dds_history_kind_DDS_HISTORY_KEEP_LAST, 1);
                }
            }
        }
        Self(q)
    }
}

impl Drop for Qos {
    fn drop(&mut self) {
        // SAFETY: created by dds_create_qos, deleted once.
        unsafe { sys::dds_delete_qos(self.0) }
    }
}

/// Explicit domain with an inline configuration (keeps tests independent of
/// the CYCLONEDDS_URI environment).
#[derive(Debug)]
pub struct Domain {
    handle: sys::dds_entity_t,
    pub id: u32,
}

impl Domain {
    pub fn with_config(id: u32, config: &str) -> Result<Self> {
        let c = CString::new(config)?;
        // SAFETY: c outlives the call; Cyclone copies the configuration.
        let h = unsafe { sys::dds_create_domain(id, c.as_ptr()) };
        check("dds_create_domain", h)?;
        Ok(Self { handle: h, id })
    }
}

impl Drop for Domain {
    fn drop(&mut self) {
        // SAFETY: valid handle deleted once.
        unsafe { sys::dds_delete(self.handle) };
    }
}

#[derive(Debug)]
pub struct Participant {
    handle: sys::dds_entity_t,
}

impl Participant {
    /// Join `domain` (uses CYCLONEDDS_URI or an explicit [`Domain`] created earlier).
    pub fn new(domain: u32) -> Result<Self> {
        // SAFETY: null qos/listener are permitted by the API.
        let h = unsafe { sys::dds_create_participant(domain, core::ptr::null(), core::ptr::null()) };
        check("dds_create_participant", h)?;
        Ok(Self { handle: h })
    }

    fn topic<T: Topic>(&self, name: &str, qos: &Qos) -> Result<sys::dds_entity_t> {
        let n = CString::new(name)?;
        // SAFETY: descriptor matches T (Topic contract); name copied by Cyclone.
        let t = unsafe { sys::dds_create_topic(self.handle, T::descriptor(), n.as_ptr(), qos.0, core::ptr::null()) };
        check("dds_create_topic", t)
    }

    pub fn writer<T: Topic>(&self, name: &str, profile: QosProfile) -> Result<Writer<'_, T>> {
        let q = Qos::new(profile);
        let t = self.topic::<T>(name, &q)?;
        // SAFETY: valid participant and topic handles.
        let w = unsafe { sys::dds_create_writer(self.handle, t, q.0, core::ptr::null()) };
        check("dds_create_writer", w)?;
        Ok(Writer { handle: w, _p: PhantomData })
    }

    pub fn reader<T: Topic>(&self, name: &str, profile: QosProfile) -> Result<Reader<'_, T>> {
        let q = Qos::new(profile);
        let t = self.topic::<T>(name, &q)?;
        // SAFETY: valid participant and topic handles.
        let r = unsafe { sys::dds_create_reader(self.handle, t, q.0, core::ptr::null()) };
        check("dds_create_reader", r)?;
        Ok(Reader { handle: r, _p: PhantomData })
    }
}

impl Drop for Participant {
    fn drop(&mut self) {
        // SAFETY: deleting the participant recursively deletes its children.
        unsafe { sys::dds_delete(self.handle) };
    }
}

/// Typed writer; borrows its participant so it cannot outlive it.
#[derive(Debug)]
pub struct Writer<'p, T: Topic> {
    handle: sys::dds_entity_t,
    _p: PhantomData<(&'p Participant, T)>,
}

impl<T: Topic> Writer<'_, T> {
    pub fn write(&self, sample: &T) -> Result<()> {
        // SAFETY: sample is a valid T matching the topic descriptor.
        let rc = unsafe { sys::dds_write(self.handle, (sample as *const T).cast::<c_void>()) };
        check("dds_write", rc).map(|_| ())
    }

    pub fn matched_readers(&self) -> Result<u32> {
        let mut st = sys::dds_publication_matched_status_t::default();
        // SAFETY: st is a valid out-pointer.
        let rc = unsafe { sys::dds_get_publication_matched_status(self.handle, &mut st) };
        check("dds_get_publication_matched_status", rc)?;
        Ok(st.current_count)
    }

    pub fn wait_for_readers(&self, n: u32, timeout: Duration) -> Result<()> {
        let t0 = Instant::now();
        while self.matched_readers()? < n {
            if t0.elapsed() > timeout {
                return Err(Error::Timeout("reader match"));
            }
            std::thread::sleep(Duration::from_millis(5));
        }
        Ok(())
    }
}

/// Typed reader.
#[derive(Debug)]
pub struct Reader<'p, T: Topic> {
    handle: sys::dds_entity_t,
    _p: PhantomData<(&'p Participant, T)>,
}

impl<T: Topic> Reader<'_, T> {
    /// Take one valid sample if available.
    pub fn take(&self) -> Result<Option<T>> {
        loop {
            let mut sample = T::default();
            let mut ptrs: [*mut c_void; 1] = [(&mut sample as *mut T).cast()];
            let mut info = sys::dds_sample_info_t::default();
            // SAFETY: one caller-owned buffer of the topic type and one info slot.
            let n = unsafe { sys::dds_take(self.handle, ptrs.as_mut_ptr(), &mut info, 1, 1) };
            check("dds_take", n)?;
            if n == 0 {
                return Ok(None);
            }
            if info.valid_data {
                return Ok(Some(sample));
            }
            // Invalid sample (dispose / unregister notification): keep draining.
        }
    }

    /// Poll until a sample arrives or the timeout expires.
    pub fn take_timeout(&self, timeout: Duration) -> Result<Option<T>> {
        let t0 = Instant::now();
        loop {
            if let Some(s) = self.take()? {
                return Ok(Some(s));
            }
            if t0.elapsed() > timeout {
                return Ok(None);
            }
            std::thread::sleep(Duration::from_micros(200));
        }
    }

    pub fn matched_writers(&self) -> Result<u32> {
        let mut st = sys::dds_subscription_matched_status_t::default();
        // SAFETY: st is a valid out-pointer.
        let rc = unsafe { sys::dds_get_subscription_matched_status(self.handle, &mut st) };
        check("dds_get_subscription_matched_status", rc)?;
        Ok(st.current_count)
    }
}

/// Host loopback profile bundled with the crate.
#[cfg(not(target_os = "macos"))]
pub const LOOPBACK_XML: &str = include_str!("../../../config/dds/helios_loopback.xml");
#[cfg(target_os = "macos")]
pub const LOOPBACK_XML: &str = include_str!("../../../config/dds/helios_loopback_macos.xml");

#[cfg(test)]
mod tests {
    use super::*;

    fn telemetry(seq: u64) -> VehicleTelemetry {
        VehicleTelemetry {
            vehicle_id: 7,
            t_ns: seq,
            speed_mps: 83.3,
            soc_pct: 71.5,
            gear: 8,
            drive_mode: 2,
            motor_torque_nm: [100.0, -100.0, 250.5, 1200.25],
            wheel_slip: [0.01, 0.02, 0.08, 0.11],
            fault_bits: 0x8000_0001,
            ..Default::default()
        }
    }

    #[test]
    fn telemetry_and_command_roundtrip_on_loopback() {
        let _d = Domain::with_config(77, LOOPBACK_XML).expect("domain");
        let p = Participant::new(77).expect("participant");
        let w = p.writer::<VehicleTelemetry>(TOPIC_TELEMETRY, QosProfile::Telemetry).expect("writer");
        let r = p.reader::<VehicleTelemetry>(TOPIC_TELEMETRY, QosProfile::Telemetry).expect("reader");
        w.wait_for_readers(1, Duration::from_secs(5)).expect("match");
        let s = telemetry(42);
        w.write(&s).expect("write");
        let got = r.take_timeout(Duration::from_secs(2)).expect("take").expect("sample");
        assert_eq!(got.t_ns, 42);
        assert_eq!(got.vehicle_id, 7);
        assert_eq!(got.fault_bits, 0x8000_0001);
        assert_eq!(got.motor_torque_nm.map(f32::to_bits), s.motor_torque_nm.map(f32::to_bits));

        // Command topic: reliable + transient-local => a late-joining reader still gets it.
        let cw = p.writer::<DriveModeRequest>(TOPIC_DRIVE_MODE, QosProfile::Command).expect("cmd writer");
        cw.write(&DriveModeRequest { vehicle_id: 7, seq: 3, mode: 2, tv_enable: true }).expect("cmd write");
        let cr = p.reader::<DriveModeRequest>(TOPIC_DRIVE_MODE, QosProfile::Command).expect("late reader");
        let c = cr.take_timeout(Duration::from_secs(3)).expect("take").expect("late-joiner sample");
        assert_eq!((c.seq, c.mode, c.tv_enable), (3, 2, true));
    }

    #[test]
    fn sustained_1khz_stream_no_reordering() {
        let _d = Domain::with_config(78, LOOPBACK_XML).expect("domain");
        let p = Participant::new(78).expect("participant");
        let w = p.writer::<VehicleTelemetry>(TOPIC_TELEMETRY, QosProfile::Stream).expect("writer");
        let r = p.reader::<VehicleTelemetry>(TOPIC_TELEMETRY, QosProfile::Stream).expect("reader");
        w.wait_for_readers(1, Duration::from_secs(5)).expect("match");
        let mut last = 0;
        let mut received = 0;
        for k in 1..=500u64 {
            w.write(&telemetry(k)).expect("write");
            if let Some(s) = r.take_timeout(Duration::from_millis(50)).expect("take") {
                assert!(s.t_ns > last, "reordered: {} after {}", s.t_ns, last);
                last = s.t_ns;
                received += 1;
            }
        }
        while let Some(s) = r.take().expect("drain") {
            assert!(s.t_ns > last);
            last = s.t_ns;
            received += 1;
        }
        assert_eq!(received, 500, "reliable keep-last-64 must not lose samples");
    }
}
